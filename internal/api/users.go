// UsersService is the RBAC account admin (System Admin only) — direct-to-DB,
// mirroring students/guardians/academics rather than proxying to a
// microservice, since it's simple CRUD over a single table.
type UsersService struct {
	pool *pgxpool.Pool
}

func NewUsersService(pool *pgxpool.Pool) *UsersService {
	return &UsersService{pool: pool}
}

func (s *UsersService) RegisterRoutes(r chi.Router) {
	r.Route("/users/", func(r chi.Router) {
		r.Use(adminOnly())
		r.Get("/", s.list)
		r.Post("/", s.create)
		r.Get("/{id}/", s.get)
		r.Put("/{id}/", s.update)
		r.Patch("/{id}/", s.update)
		r.Delete("/{id}/", s.delete)
	})
}

type UserOut struct {
	ID                 uuid.UUID `json:"id"`
	Email              string    `json:"email"`
	FirstName          string    `json:"first_name"`
	LastName           string    `json:"last_name"`
	FullName           string    `json:"full_name"`
	Phone              string    `json:"phone"`
	Role               string    `json:"role"`
	Portal             string    `json:"portal"`
	IsActive           bool      `json:"is_active"`
	MustChangePassword bool      `json:"must_change_password"`
	CreatedAt          time.Time `json:"created_at"`
}

const userCols = `id, email, first_name, last_name, phone, role, is_active, must_change_password, created_at`

func scanUser(row interface{ Scan(dest ...interface{}) error }) (UserOut, error) {
	var u UserOut
	var role string
	err := row.Scan(&u.ID, &u.Email, &u.FirstName, &u.LastName, &u.Phone, &role, &u.IsActive, &u.MustChangePassword, &u.CreatedAt)
	u.Role = strings.ToUpper(role)
	u.Portal = string(types.RoleToPortal(types.Role(u.Role)))
	u.FullName = strings.TrimSpace(u.FirstName + " " + u.LastName)
	return u, err
}

func (s *UsersService) list(w http.ResponseWriter, r *http.Request) {
	where := []string{"true"}
	args := []interface{}{}
	argIdx := 1
	if v := r.URL.Query().Get("role"); v != "" {
		where = append(where, "role = $"+strconv.Itoa(argIdx))
		args = append(args, strings.ToLower(v))
		argIdx++
	}
	if v := strings.TrimSpace(r.URL.Query().Get("search")); v != "" {
		where = append(where, "(first_name ILIKE $"+strconv.Itoa(argIdx)+" OR last_name ILIKE $"+strconv.Itoa(argIdx)+" OR email ILIKE $"+strconv.Itoa(argIdx)+")")
		args = append(args, "%"+v+"%")
		argIdx++
	}
	page, pageSize, offset := pageParams(r)
	var total int
	_ = s.pool.QueryRow(r.Context(), "SELECT COUNT(*) FROM users WHERE "+joinAnd(where), args...).Scan(&total)

	q := "SELECT " + userCols + " FROM users WHERE " + joinAnd(where) +
		" ORDER BY created_at DESC LIMIT $" + strconv.Itoa(argIdx) + " OFFSET $" + strconv.Itoa(argIdx+1)
	args = append(args, pageSize, offset)
	rows, err := s.pool.Query(r.Context(), q, args...)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	defer rows.Close()
	out := []UserOut{}
	for rows.Next() {
		u, err := scanUser(rows)
		if err != nil {
			continue
		}
		out = append(out, u)
	}
	httpx.JSON(w, http.StatusOK, map[string]interface{}{"results": out, "count": total, "page": page, "page_size": pageSize})
}

func (s *UsersService) get(w http.ResponseWriter, r *http.Request) {
	id, err := idParam(r)
	if err != nil {
		httpx.ErrBadRequest(w, "invalid id")
		return
	}
	u, err := scanUser(s.pool.QueryRow(r.Context(), "SELECT "+userCols+" FROM users WHERE id = $1", id))
	if err != nil {
		httpx.ErrNotFound(w, "user not found")
		return
	}
	httpx.JSON(w, http.StatusOK, u)
}

func generateTempPassword() string {
	const charset = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789!@#$%"
	b := make([]byte, 12)
	for i := range b {
		n, _ := rand.Int(rand.Reader, big.NewInt(int64(len(charset))))
		b[i] = charset[n.Int64()]
	}
	return string(b)
}

func (s *UsersService) create(w http.ResponseWriter, r *http.Request) {
	var body struct {
		FirstName string `json:"first_name" validate:"required"`
		LastName  string `json:"last_name"`
		Email     string `json:"email" validate:"required,email"`
		Role      string `json:"role" validate:"required"`
		Phone     string `json:"phone"`
		Password  string `json:"password"`
	}
	if err := httpx.BindAndValidate(r, &body); err != nil {
		httpx.ErrBadRequest(w, err.Error())
		return
	}
	role := types.Role(strings.ToUpper(body.Role))
	if !types.IsValidRole(role) {
		httpx.ErrBadRequest(w, "invalid role")
		return
	}
	autoGenerated := body.Password == ""
	plainPassword := body.Password
	if autoGenerated {
		plainPassword = generateTempPassword()
	}
	hash, err := crypto.HashPassword(plainPassword)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	id := uuid.New()
	isStaff := role != types.RoleStudent && role != types.RoleParent
	_, err = s.pool.Exec(r.Context(), `
		INSERT INTO users (id, email, password, first_name, last_name, phone, role, is_staff,
			is_active, must_change_password, date_joined, created_at, updated_at)
		VALUES ($1, $2, $3, $4, $5, $6, $7, $8, true, $9, NOW(), NOW(), NOW())`,
		id, body.Email, hash, body.FirstName, body.LastName, body.Phone, strings.ToLower(string(role)), isStaff, autoGenerated)
	if err != nil {
		if strings.Contains(err.Error(), "users_email_key") {
			httpx.ErrConflict(w, "a user with this email already exists")
			return
		}
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	u, err := scanUser(s.pool.QueryRow(r.Context(), "SELECT "+userCols+" FROM users WHERE id = $1", id))
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	resp := map[string]interface{}{"user": u}
	if autoGenerated {
		// Only ever shown once — the hash is one-way from here on, so this
		// is the admin's only chance to see/share the temporary password.
		resp["temporary_password"] = plainPassword
	}
	httpx.JSON(w, http.StatusCreated, resp)
}

func (s *UsersService) update(w http.ResponseWriter, r *http.Request) {
	id, err := idParam(r)
	if err != nil {
		httpx.ErrBadRequest(w, "invalid id")
		return
	}
	var body struct {
		FirstName *string `json:"first_name,omitempty"`
		LastName  *string `json:"last_name,omitempty"`
		Phone     *string `json:"phone,omitempty"`
		Role      *string `json:"role,omitempty"`
		IsActive  *bool   `json:"is_active,omitempty"`
	}
	if err := json.NewDecoder(r.Body).Decode(&body); err != nil {
		httpx.ErrBadRequest(w, err.Error())
		return
	}
	if body.Role != nil {
		role := types.Role(strings.ToUpper(*body.Role))
		if !types.IsValidRole(role) {
			httpx.ErrBadRequest(w, "invalid role")
			return
		}
		lower := strings.ToLower(string(role))
		body.Role = &lower
	}
	_, err = s.pool.Exec(r.Context(), `
		UPDATE users SET
			first_name = COALESCE($1, first_name),
			last_name = COALESCE($2, last_name),
			phone = COALESCE($3, phone),
			role = COALESCE($4, role),
			is_active = COALESCE($5, is_active),
			updated_at = NOW()
		WHERE id = $6`,
		body.FirstName, body.LastName, body.Phone, body.Role, body.IsActive, id)
	if err != nil {
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	u, err := scanUser(s.pool.QueryRow(r.Context(), "SELECT "+userCols+" FROM users WHERE id = $1", id))
	if err != nil {
		httpx.ErrNotFound(w, "user not found")
		return
	}
	httpx.JSON(w, http.StatusOK, u)
}

func (s *UsersService) delete(w http.ResponseWriter, r *http.Request) {
	id, err := idParam(r)
	if err != nil {
		httpx.ErrBadRequest(w, "invalid id")
		return
	}
	if callerID, ok := r.Context().Value("user_id").(uuid.UUID); ok && callerID == id {
		httpx.ErrBadRequest(w, "cannot delete your own account")
		return
	}
	if _, err := s.pool.Exec(r.Context(), "DELETE FROM users WHERE id = $1", id); err != nil {
		httpx.Error(w, http.StatusInternalServerError, err)
		return
	}
	httpx.JSON(w, http.StatusOK, map[string]string{"status": "deleted", "id": id.String()})
}
